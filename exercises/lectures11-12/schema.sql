-- Run in the intended coursework Snowflake account and warehouse.
CREATE DATABASE IF NOT EXISTS TSI_CLASSWORK_11_12;
CREATE SCHEMA IF NOT EXISTS TSI_CLASSWORK_11_12.MY_SCHEMA;
CREATE TABLE IF NOT EXISTS TSI_CLASSWORK_11_12.MY_SCHEMA.BANKING_MESSAGES (
  TRANSACTION_ID VARCHAR(200) NOT NULL,
  CARD_ID VARCHAR(200) NOT NULL,
  TRUSTEE_EXTERNAL_ID VARCHAR(200) NOT NULL,
  CHANNEL_TYPE VARCHAR(200) NOT NULL,
  STATUS VARCHAR(200) NOT NULL,
  STATUS_TIMESTAMP TIMESTAMP_TZ NOT NULL,
  EVENT_TIMESTAMP TIMESTAMP_TZ NOT NULL,
  MESSAGE VARCHAR(2000) NOT NULL,
  API_VERSION VARCHAR(20) NOT NULL,
  API_INFO VARIANT NOT NULL,
  RECEIVED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
SELECT * FROM TSI_CLASSWORK_11_12.MY_SCHEMA.BANKING_MESSAGES ORDER BY RECEIVED_AT DESC;
